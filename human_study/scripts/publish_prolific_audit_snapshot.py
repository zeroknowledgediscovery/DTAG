#!/usr/bin/env python3
"""Publish a minimal, public-safe, versioned aggregate snapshot from a DTAG private audit.

Reads the protected aggregate summary.json from audit_all_dtag_prolific.py.
Exports aggregate study, cohort, and invoice-reconciliation counts only.
Never reads or exports PRIVATE_*.csv or participant-level IDs.

Example:
  python3 human_study/scripts/publish_prolific_audit_snapshot.py \\
    --summary /tmp/dtag_full_audit/summary.json \\
    --dem-pdf /private/DEMOCRATIC_recruitment_right_push_prolific_summary_detailed_6ae37b8688d760488b8df1b0.pdf \\
    --rep-pdf /private/REPUBLICAN_RECRUIOT_right_push_prolific_summary_detailed_6ae3d74f4c7ff7370986b1e4.pdf \\
    --out human_study/reports/prolific_audit_YYYY-MM-DD.json

Review the generated snapshot, especially issue counts, before git add/commit.
"""
from __future__ import annotations

import argparse
from datetime import date
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CAMPAIGN_MAP = ROOT / "config" / "prolific_campaign_map.json"
STUDY_FIELDS = (
    "study_id", "study_name", "baseline_question_count", "expected_policy",
    "sessions_total", "consented_sessions", "unique_consented_pids",
    "started_sessions", "completed_20_sessions", "unique_completed_20_pids",
    "gcs_final_20_sessions", "unique_gcs_final_20_pids",
    "not_complete_sessions", "missing_consent_pid", "distinct_config_hashes",
    "earliest_created", "latest_updated",
)
COHORT_FIELDS = (
    "study_id", "prolific_study_id", "recruitment_label", "arm",
    "declared_planned_slots", "sessions_total", "consented_sessions",
    "unique_consented_pids", "completed_20_sessions",
    "unique_completed_20_pids", "gcs_final_20_sessions",
    "unique_gcs_final_20_pids", "missing_consent_pid",
    "distinct_config_hashes", "earliest_created", "latest_updated",
)
ROSTER_FIELDS = (
    "prolific_campaign_id_declared", "pdf_study_title", "prolific_summary_id",
    "approved_unique_pids", "dtag_pids_linked", "linked_20_answers",
    "linked_archived_final_20", "approved_pids_with_other_sessions",
    "paid_without_exact_dtag_link",
)
COUNT_FIELDS = (
    "firestore_session_records", "gcs_final_json", "distinct_dtag_studies",
    "unique_consented_prolific_ids_all_studies",
)
ALLOWED_SCAN_MODES = ("FULL_COLLECTION_GROUP", "KNOWN_AND_GCS_DISCOVERED_STUDIES_ONLY")


def pick(obj: dict, keys: tuple[str, ...]) -> dict:
    if not isinstance(obj, dict):
        raise ValueError("Expected aggregate dictionary, not participant-level data")
    return {k: obj[k] for k in keys if k in obj}


def digest(path: Path | None) -> str | None:
    if path is None:
        return None
    h = hashlib.sha256()
    with path.open("rb") as f:
        while block := f.read(1024 * 1024):
            h.update(block)
    return h.hexdigest()


def parse_policies(value):
    if not value:
        return {}
    if isinstance(value, str):
        value = json.loads(value)
    if not isinstance(value, dict) or any(
        not isinstance(k, str) or not isinstance(v, int) or isinstance(v, bool) or v < 0
        for k, v in value.items()
    ):
        raise ValueError("Invalid aggregate policy histogram")
    return dict(sorted(value.items()))


def scrub_rows(rows, fields, policies=False):
    if not isinstance(rows, list):
        raise ValueError("Expected aggregate row list")
    output = []
    for row in rows:
        r = pick(row, fields)
        if policies:
            r["observed_policy_distribution"] = parse_policies(
                row.get("observed_policy_distribution"))
        output.append(r)
    return output


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--summary", required=True, type=Path,
                   help="Private aggregate summary.json generated by full DTAG audit")
    p.add_argument("--out", required=True, type=Path,
                   help="New public-safe aggregate snapshot JSON path")
    p.add_argument("--snapshot-date", type=date.fromisoformat, default=None)
    p.add_argument("--dem-pdf", type=Path, default=None, help="Optional private invoice; saves SHA256, not content")
    p.add_argument("--rep-pdf", type=Path, default=None, help="Optional private invoice; saves SHA256, not content")
    args = p.parse_args()
    if args.out.exists():
        p.error("Output exists; snapshots are immutable. Select a new filename or inspect manually.")
    data = json.loads(args.summary.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or not all(k in data for k in
            ("counts", "studies", "cohorts", "paid_rosters", "issue_type_counts", "scan_mode")):
        p.error("Unrecognized full-audit summary format")
    if data["scan_mode"] not in ALLOWED_SCAN_MODES:
        p.error("Unrecognized Firestore scan mode")
    campaign_data = json.loads(CAMPAIGN_MAP.read_text(encoding="utf-8"))
    known_campaigns = campaign_data["campaigns"]
    studies = scrub_rows(data["studies"], STUDY_FIELDS, policies=True)
    cohorts = scrub_rows(data["cohorts"], COHORT_FIELDS)
    rosters = scrub_rows(data["paid_rosters"], ROSTER_FIELDS)
    for row in studies:
        if not isinstance(row.get("study_id"), str):
            p.error("Study row missing study_id")
        for metric in ("sessions_total", "unique_consented_pids", "completed_20_sessions",
                       "gcs_final_20_sessions"):
            n = row.get(metric)
            if not isinstance(n, int) or isinstance(n, bool) or n < 0:
                p.error("Invalid aggregate " + metric + " for " + row["study_id"])
        if any(row[m] > row["sessions_total"] for m in
               ("unique_consented_pids", "completed_20_sessions", "gcs_final_20_sessions")):
            p.error("Invalid count exceeds sessions for " + row["study_id"])
    for row in rosters:
        cid = row.get("prolific_campaign_id_declared")
        if cid not in known_campaigns:
            p.error("Unknown paid roster campaign: " + str(cid))
        if any(not isinstance(row.get(k), int) or row[k] < 0 for k in (
                "approved_unique_pids", "dtag_pids_linked", "linked_20_answers",
                "linked_archived_final_20", "paid_without_exact_dtag_link")):
            p.error("Invalid paid-roster counts")
        if row["dtag_pids_linked"] + row["paid_without_exact_dtag_link"] != row["approved_unique_pids"]:
            p.error("Paid-roster reconciliation does not sum to approved participants")
    if not isinstance(data["issue_type_counts"], dict) or any(
            not re.fullmatch(r"[A-Z][A-Z0-9_]{0,100}", k)
            or not isinstance(v, int) or v < 0
            for k, v in data["issue_type_counts"].items()):
        p.error("Invalid issue-type aggregate counts")
    source_date = (data.get("generated_utc") or "")[:10]
    snapshot_date = args.snapshot_date or (date.fromisoformat(source_date)
                                           if source_date else date.today())
    rosters_by_id = {r["prolific_campaign_id_declared"]: r for r in rosters}
    expected = ("6ae37b8688d760488b8df1b0", "6ae3d74f4c7ff7370986b1e4")
    invoice_hashes = {
        "DTAG_right_DEM": digest(args.dem_pdf),
        "DTAG_right_REP": digest(args.rep_pdf),
    }
    out = {
        "schema_version": 1,
        "snapshot_date": snapshot_date.isoformat(),
        "snapshot_kind": "generated-from-private-aggregate-audit",
        "provenance": {
            "audit_script": "human_study/scripts/audit_all_dtag_prolific.py",
            "firestore_project": "pkcsaas-01",
            "firestore_database": "dtag-human-pilot",
            "gcs_bucket": "pkcsaas-01-dtag-study-data",
            "firestore_scan_mode": data["scan_mode"],
            "audit_generated_utc": data.get("generated_utc"),
            "source_summary_sha256": digest(args.summary),
            "pdf_source_sha256": invoice_hashes,
        },
        "unit_definitions": {
            "sessions_total": "Firestore session records, not unique participants",
            "unique_consented_pids": "Distinct Prolific participant IDs among consented sessions",
            "completed_20_sessions": "Sessions with twenty recorded adaptive answers",
            "gcs_final_20_sessions": "Sessions with twenty adaptive answers in a GCS final archive",
            "approved_unique_pids": "Distinct approved paid Prolific invoice participant IDs",
        },
        "total_counts": pick(data["counts"], COUNT_FIELDS),
        "study_inventory": studies,
        "cohort_inventory": cohorts,
        "approved_payment_roster_reconciliation": rosters,
        "issue_type_counts": dict(sorted(data["issue_type_counts"].items())),
        "checks": {
            "latest_campaign_ids_present": all(cid in rosters_by_id for cid in expected),
            "all_recent_approved_have_20_answer_archive": all(
                rosters_by_id.get(cid, {}).get("approved_unique_pids") ==
                rosters_by_id.get(cid, {}).get("linked_archived_final_20")
                for cid in expected if cid in rosters_by_id),
            "issues_remaining": bool(data["issue_type_counts"]),
            "exhaustive_firestore_scan": data["scan_mode"] == "FULL_COLLECTION_GROUP",
        },
        "privacy": "AGGREGATE_ONLY; no participant PID, session ID, response text, or invoice PDF",
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print("Created sanitized aggregate snapshot:", args.out)
    print("All approved recent participants have GCS finals:",
          out["checks"]["all_recent_approved_have_20_answer_archive"])
    print("Outstanding issue types:", len(out["issue_type_counts"]))
    print("Review before committing; never commit the source PDFs or PRIVATE_*.csv.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
