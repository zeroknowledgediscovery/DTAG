#!/usr/bin/env python3
"""Render two NHB theme-level explanatory tables from PUBLIC aggregate CSVs.

Run from the DTAG checkout:
  python3 human_study/scripts/render_nhb_theme_tables.py

This script never reads private participant data. It verifies that seven
nonoverlapping topic categories exhaust all 20 observations per person
for the Left and Right arms before constructing a signed thematic
accounting table. It does not compute true inter-theme conditional
effects; such analyses require model re-evaluation on archival answers.
"""
from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT = ROOT / "tex" / "Figures" / "nhb_explanatory"
TOPICS = (
    ("civil_liberties", "Civil liberties"),
    ("religion_culture", "Religion and culture"),
    ("sexual_reproductive", "Sexual and reproductive attitudes"),
    ("spending_program", "Public spending and programs"),
    ("institutions", "Institutional confidence"),
    ("political_ratings", "Political evaluations"),
    ("other", "Other questions"),
)
GROUPS = (
    ("right_initially_left_q4_flagged", "Initially Left, Q4-flagged", 19),
    ("right_initially_left_q4_unflagged", "Initially Left, Q4-unflagged", 10),
    ("right_initially_right", "Initially Right", 9),
)


def read_csv(path):
    with path.open(encoding="utf-8-sig", newline="") as h:
        return list(csv.DictReader(h))


def indexed(rows, keys):
    result = {}
    for row in rows:
        key = tuple(row[col] for col in keys)
        if key in result:
            raise ValueError(f"Duplicate aggregate key: {key}")
        result[key] = row
    return result


def close(a, b):
    if not math.isclose(a, b, abs_tol=2e-7, rel_tol=0):
        raise ValueError(f"Aggregate failed consistency check: {a} != {b}")


def number(row, key):
    return float(row[key])


def fmt(v):
    return f"{v:+.4f}"


def table_one(topics, stages):
    arms = (("left_all", 21), ("right_all", 38))
    for arm, n in arms:
        detail = [v for (g, st, cat), v in topics.items()
                  if (g, st) == (arm, "all")]
        if {v["topic"] for v in detail} != {t for t, _ in TOPICS}:
            raise ValueError(f"Expected seven exhaustive themes for {arm}")
        close(sum(int(v["n_selections"]) for v in detail), 20 * n)
        avg = sum(number(v, "sum_signed") for v in detail) / n
        close(avg, number(stages[(arm, "all")], "mean_signed_displacement"))
    p = []
    p.extend([
        "% Generated by render_nhb_theme_tables.py from committed public aggregates.",
        "% Positive means movement TOWARD the question policy's requested pole.",
        r"\begin{table}[!t]",
        r"\centering",
        r"\caption{\textbf{Thematic composition of human directional index updates.} "
        r"Question targets are grouped into seven mutually exclusive exploratory themes. "
        r"For each policy, the number (percentage) of selected questions and "
        r"the net directional index increment per participant are reported. "
        r"Positive increments are in the policy's intended direction; negative "
        r"increments oppose it. Unlike sums of favorable increments, net "
        r"contributions telescope to the observed policy mean displacement. "
        r"These are descriptive, ordered observations, not causal effects "
        r"of question themes or independent cross-theme influence.}",
        r"\label{tab:nhb-theme-policy}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabularx}{\linewidth}{@{}Xrrrr@{}}",
        r"\toprule",
        r" & \multicolumn{2}{c}{Left ($n=21$)} & \multicolumn{2}{c}{Right ($n=38$)} \\",
        r"\cmidrule(lr){2-3}\cmidrule(l){4-5}",
        r"Theme & Selections & Mean signed & Selections & Mean signed \\",
        r"\midrule",
    ])
    for topic, label in TOPICS:
        items = [topics[(arm, "all", topic)] for arm, _ in arms]
        left, right = items
        def count(row, n):
            return f'{int(row["n_selections"])} ({100*int(row["n_selections"])/(20*n):.1f}\\%)'
        p.append(f"{label} & {count(left, 21)} & {fmt(number(left,'sum_signed')/21)}"
                 f" & {count(right, 38)} & {fmt(number(right,'sum_signed')/38)}" + r" \\")
    p.extend([
        r"\midrule",
        (r"\textbf{Total} & 420 (100\%) & "
         + fmt(number(stages[("left_all", "all")], "mean_signed_displacement"))
         + r" & 760 (100\%) & "
         + fmt(number(stages[("right_all", "all")], "mean_signed_displacement"))
         + r" \\"),
        r"\bottomrule",
        r"\end{tabularx}",
        r"\end{table}",
        "",
    ])
    return "\n".join(p)


def table_two(topics, stages):
    p = [
        "% Generated by render_nhb_theme_tables.py from committed public aggregates.",
        "% Q4 groups are DEFINED by Q4 displacement: comparisons are descriptive.",
        r"\begin{table}[!t]",
        r"\centering",
        r"\caption{\textbf{Early thematic contributions and subsequent displacement under Right-directed questioning.} "
        r"Three baseline/Q4-defined Right-push subgroups are compared. "
        r"All changes are signed rightward and averaged per participant. "
        r"Civil-liberties and religion/culture columns sum the net increments "
        r"following early questions (1--4) in those themes. "
        r"An em dash indicates a suppressed aggregate, not zero. "
        r"Q4-flagged and unflagged trajectories differ by definition before "
        r"question five; their later differences remain observational.}",
        r"\label{tab:nhb-theme-resistance}",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\begin{tabularx}{\linewidth}{@{}Xrrrrr@{}}",
        r"\toprule",
        r"Baseline and Q4 response & $n$ & $\overline{\Delta}_{1:4}$"
        r" & $\overline{\Delta}_{5:20}$ & Civil liberties$_{1:4}$"
        r" & Religion/culture$_{1:4}$ \\",
        r"\midrule",
    ]
    for key, label, n in GROUPS:
        early = stages[(key, "early")]
        late = stages[(key, "late")]
        overall = stages[(key, "all")]
        if int(early["n_sessions"]) != n or int(late["n_sessions"]) != n:
            raise ValueError(f"Unexpected subgroup sample size: {key}")
        close(number(early,"mean_signed_displacement")
              + number(late,"mean_signed_displacement"),
              number(overall,"mean_signed_displacement"))
        def theme_mean(cat):
            value = topics.get((key, "early", cat))
            return fmt(number(value,"sum_signed") / n) if value else r"---"
        p.append(f"{label} & {n} & {fmt(number(early,'mean_signed_displacement'))}"
                 f" & {fmt(number(late,'mean_signed_displacement'))}"
                 f" & {theme_mean('civil_liberties')}"
                 f" & {theme_mean('religion_culture')}" + r" \\")
    p.extend([r"\bottomrule", r"\end{tabularx}", r"\end{table}", ""])
    return "\n".join(p)


def render(folder=DEFAULT):
    folder = Path(folder)
    topics = indexed(read_csv(folder/"nhb_question_topics.csv"),
                     ("group", "stage", "topic"))
    stages = indexed(read_csv(folder/"nhb_resistance_stage_metrics.csv"),
                     ("group", "stage"))
    output = {
        "nhb_theme_policy_table.tex": table_one(topics, stages),
        "nhb_theme_resistance_table.tex": table_two(topics, stages),
    }
    for name, content in output.items():
        (folder / name).write_text(content, encoding="utf-8")
        print("Generated:", folder / name)
    return output


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--aggregate-dir", type=Path, default=DEFAULT)
    args = parser.parse_args()
    render(args.aggregate_dir)
